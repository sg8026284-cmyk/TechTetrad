"""Unified patch exporter and Draft Pull Request generator."""

import os
import json
from typing import List, Dict, Any
from ..models import AuditReport, GeneratedPatch, PatchValidationStatus


def export_unified_patches(report: AuditReport, output_dir: str) -> List[str]:
    """Export unified diff patch files (.patch) to the specified directory."""
    os.makedirs(output_dir, exist_ok=True)
    exported_files = []

    for patch in report.patches:
        filename = f"{patch.patch_id}_{os.path.basename(patch.target_file)}.patch"
        out_path = os.path.join(output_dir, filename)
        with open(out_path, "w", encoding="utf-8") as f:
            f.write(patch.unified_diff)
        exported_files.append(out_path)

    # Also export combined patch
    if report.patches:
        combined_path = os.path.join(output_dir, "combined_remediation.patch")
        with open(combined_path, "w", encoding="utf-8") as f:
            for patch in report.patches:
                f.write(f"# Patch {patch.patch_id} for {patch.target_file} ({patch.validation_status.value})\n")
                f.write(patch.unified_diff)
                f.write("\n\n")
        exported_files.append(combined_path)

    return exported_files


def export_draft_pull_request(report: AuditReport, output_path: str) -> Dict[str, Any]:
    """Generate reviewable Draft Pull Request payload (JSON) without auto-merging."""
    passed_patches = [p for p in report.patches if p.validation_status == PatchValidationStatus.PASSED]

    pr_title = f"[Security Remediation] Automated Multi-Agent Patches for {len(passed_patches)} Issues"
    
    body_lines = [
        "## Automated Security Remediation Pull Request (Draft)",
        "",
        "> **Note**: This pull request was automatically generated by the Multi-Agent Codebase Vulnerability Auditor.",
        "> Changes are staged as a draft and have been validated against AST syntax and security elimination checks.",
        "",
        "### Addressed Findings & Validation Results",
        ""
    ]

    for p in report.patches:
        body_lines.append(f"- **Patch `{p.patch_id}`** on `{p.target_file}`: **{p.validation_status.value}**")
        for note in p.validation_notes:
            body_lines.append(f"  - {note}")

    body_lines.append("\n### Reviewer Instructions")
    body_lines.append("1. Inspect the attached unified diffs.")
    body_lines.append("2. Execute repository unit and regression tests.")
    body_lines.append("3. Approve and merge when satisfied.")

    pr_payload = {
        "title": pr_title,
        "head_branch": f"security-fix-{report.scan_id.lower()}",
        "base_branch": "main",
        "is_draft": True,
        "body": "\n".join(body_lines),
        "files_changed": [p.target_file for p in report.patches],
        "patches_count": len(report.patches),
        "validated_count": len(passed_patches)
    }

    with open(output_path, "w", encoding="utf-8") as f:
        json.dump(pr_payload, f, indent=2)

    return pr_payload

